"""Build the site's static snapshot from the supplied XLSX, without changing it.

Usage: python3 scripts/import-tracker.py '/path/Issue Tracker - Locations Updated.xlsx'
Only the Issues- Realtime fields used by the dashboard are exported.
"""
import datetime as dt
import hashlib
import json
from pathlib import Path
import posixpath
import re
import sys
import xml.etree.ElementTree as ET
import zipfile

NS = {'x': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
REL = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'


def cell_value(cell, strings):
    kind = cell.get('t')
    text = cell.findtext('x:v', default='', namespaces=NS)
    if kind == 's':
        return strings[int(text)] if text else ''
    if kind == 'inlineStr':
        return ''.join(cell.find('x:is', NS).itertext())
    if kind == 'e':
        return ''  # An Excel error is not incident data.
    return text


def date_text(text, epoch):
    if not text or not re.fullmatch(r'\d+(?:\.\d+)?', text):
        return text
    if float(text) <= 0:
        return ''
    return (epoch + dt.timedelta(seconds=round(float(text) * 86400))).strftime('%d/%m/%Y %H:%M:%S')


def read_tracker(path):
    with zipfile.ZipFile(path) as archive:
        book = ET.fromstring(archive.read('xl/workbook.xml'))
        sheet = next(s for s in book.find('x:sheets', NS) if s.get('name') == 'Issues- Realtime')
        rels = ET.fromstring(archive.read('xl/_rels/workbook.xml.rels'))
        target = next(r.get('Target') for r in rels if r.get('Id') == sheet.get(f'{{{REL}}}id'))
        part = target.lstrip('/') if target.startswith('/') else posixpath.normpath('xl/' + target)
        strings = [''.join(s.itertext()) for s in ET.fromstring(archive.read('xl/sharedStrings.xml'))]
        props = book.find('x:workbookPr', NS)
        is_1904 = props is not None and props.get('date1904') in ('1', 'true')
        epoch = dt.datetime(1904, 1, 1) if is_1904 else dt.datetime(1899, 12, 30)
        result = []
        seen = set()
        with archive.open(part) as stream:
            for _, row in ET.iterparse(stream, events=('end',)):
                if row.tag != f'{{{NS["x"]}}}row':
                    continue
                number = int(row.get('r'))
                cells = {re.sub(r'\d', '', c.get('r')): cell_value(c, strings) for c in row}
                row.clear()
                if number == 1:
                    for col, title in {'B': 'Issue Id', 'D': 'Vehicle Number', 'J': 'Sub-request', 'P': 'Location'}.items():
                        if cells.get(col, '').strip() != title:
                            raise ValueError(f'Unexpected tracker layout in {col}1; expected {title}')
                    continue
                # Ignore formatted/pre-numbered empty rows, while retaining all actual incidents.
                if not any(cells.get(col, '').strip() for col in ('C', 'D', 'J', 'K', 'L', 'M')):
                    continue
                issue = cells.get('B', '').strip() or f'ROW-{number}'
                if issue in seen:
                    raise ValueError(f'Duplicate issue ID {issue} at row {number}')
                seen.add(issue)
                get = lambda col: cells.get(col, '')
                result.append([
                    issue, get('C'), get('D'), date_text(get('E'), epoch), get('F'), get('G'),
                    get('H'), get('J'), None, get('K'), get('M'), get('P'), None, None,
                    get('R'), date_text(get('S'), epoch), get('O'), get('T'), get('X'), get('L'), number,
                ])
    if not result:
        raise ValueError('No incident records found; existing snapshot was not replaced')
    return result


def main():
    source = Path(sys.argv[1]).expanduser().resolve()
    rows = read_tracker(source)
    metadata = {
        'name': source.name, 'sheet': 'Issues- Realtime',
        'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
        'incidentCount': len(rows), 'mode': 'workbook-snapshot',
    }
    root = Path(__file__).resolve().parent.parent
    # Separate JS file rather than inline HTML; escape HTML delimiters defensively.
    encode = lambda obj: json.dumps(obj, ensure_ascii=True, separators=(',', ':')).replace('<', '\\u003c')
    output = '// Generated by scripts/import-tracker.py from the location-updated workbook.\n'
    output += 'window.WORKBOOK_SOURCE = ' + encode(metadata) + ';\n'
    output += 'window.INITIAL_INCIDENT_DATA = [\n' + ',\n'.join(encode(row) for row in rows) + '\n];\n'
    (root / 'data-snapshot.js').write_text(output, encoding='utf-8')
    print(json.dumps(metadata, indent=2))


if __name__ == '__main__':
    main()
